import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../src/lib/desktopApi.js', import.meta.url), 'utf8');
const events = [];
globalThis.window = { dispatchEvent: event => events.push(event.type) };
globalThis.fetch = async () => ({ ok: true, status: 200 });
const web = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
await web.apiFetch('/api/v1/progression/xp', { method: 'POST' });
assert.deepEqual(events, ['navis:progression-changed']);
await web.apiFetch('/api/v1/progression/xp');
assert.equal(events.length, 1);
globalThis.fetch = async () => ({ ok: false, status: 422 });
await web.apiFetch('/api/v1/progression/xp', { method: 'POST' });
assert.equal(events.length, 1, 'failed writes must not signal success');
window.__TAURI_INTERNALS__ = {};
globalThis.fetch = () => { throw Error('native must not contact FastAPI'); };
const calls = [];
globalThis.fixtureInvoke = async (command, args) => {
  calls.push({ command, args });
  return { status: 200, body: { total_xp: 1010, level: 2, history: [] } };
};
const nativeSource = source.replace("const { invoke } = await import('@tauri-apps/api/core');", 'const invoke = globalThis.fixtureInvoke;');
const native = await import(`data:text/javascript;base64,${Buffer.from(nativeSource).toString('base64')}`);
const response = await native.apiFetch('/api/v1/progression/xp?entity_id=keeper');
assert.equal((await response.json()).level, 2);
assert.equal(calls[0].command, 'progression_request');
assert.equal(calls[0].args.path, '/api/v1/progression/xp?entity_id=keeper');
await native.apiFetch('/api/v1/progression/xp', { method: 'POST', body: JSON.stringify({ award_id: 'fixture' }) });
assert.equal(calls[1].args.body.award_id, 'fixture');
assert.equal(events.length, 2);
console.log('Progression web/native adapter and refresh behavior passed.');
